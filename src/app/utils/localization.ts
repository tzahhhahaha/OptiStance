export const localeFromSetting = (setting: string | undefined): AppLocale =>
  LOCALE_BY_SETTING[setting ?? ''] ?? 'en';

let activeSetting: string | undefined;

export const setAppLanguage = (setting: string): void => {
  activeSetting = setting;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = localeFromSetting(setting);
  }
};

const persistedLanguage = (): string => {
  try {
    const stored = localStorage.getItem('optistance_settings');
    return stored ? (JSON.parse(stored) as { language?: string }).language ?? '' : '';
  } catch {
    return '';
  }
};

export const translate = (source: string, setting?: string): string => {
  const selectedSetting = setting ?? activeSetting ?? persistedLanguage();
  const locale = LOCALE_BY_SETTING[selectedSetting] ?? (selectedSetting in MESSAGES ? selectedSetting as AppLocale : 'en');
  if (locale === 'en') return source;
  return MESSAGES[locale as Exclude<AppLocale, 'en'>][source] ?? source;
};